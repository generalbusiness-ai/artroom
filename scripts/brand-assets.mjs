// Only these reviewed public files are embedded in the Worker. No directory scan.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
const here = path => fileURLToPath(new URL(path, import.meta.url));
export const MODULE = here("../apps/room/brand/assets.ts");
export const PUBLIC_BRAND_FILES = {
  "fonts.css": ["fonts.css", "text/css; charset=utf-8"],
  "fonts/LICENSE-OpenRunde.txt": ["fonts/LICENSE-OpenRunde.txt", "text/plain; charset=utf-8"],
  "fonts/LICENSE-Teletype33.txt": ["fonts/LICENSE-Teletype33.txt", "text/plain; charset=utf-8"],
  "fonts/LICENSE-SometypeMono.txt": ["fonts/LICENSE-SometypeMono.txt", "text/plain; charset=utf-8"],
  "fonts/OpenRunde-Regular.woff2": ["fonts/OpenRunde-Regular.woff2", "font/woff2"],
  "fonts/OpenRunde-Medium.woff2": ["fonts/OpenRunde-Medium.woff2", "font/woff2"],
  "fonts/OpenRunde-Semibold.woff2": ["fonts/OpenRunde-Semibold.woff2", "font/woff2"],
  "fonts/OpenRunde-Bold.woff2": ["fonts/OpenRunde-Bold.woff2", "font/woff2"],
  "fonts/SometypeMono-Regular.woff2": ["fonts/SometypeMono-Regular.woff2", "font/woff2"],
  "fonts/SometypeMono-Medium.woff2": ["fonts/SometypeMono-Medium.woff2", "font/woff2"],
  "fonts/Teletype33-Narrow.ttf": ["fonts/Teletype33-Narrow.ttf", "font/ttf"],
  "fonts/Teletype33.ttf": ["fonts/Teletype33.ttf", "font/ttf"],
  "favicon.svg": ["dist/favicon.svg", "image/svg+xml"],
  "favicon.ico": ["dist/favicon.ico", "image/vnd.microsoft.icon"],
  "dap-wordmark.svg": ["dap-wordmark-green.svg", "image/svg+xml"],
  "dap-wordmark-mono-123f2b.svg": ["dist/dap-wordmark-mono-123f2b.svg", "image/svg+xml"],
  "dap-wordmark-white.svg": ["dist/dap-wordmark-white.svg", "image/svg+xml"],
};
export async function brandAssets() {
  const rows = [];
  const hashes = [];
  for (const [name, [source, type]] of Object.entries(PUBLIC_BRAND_FILES)) {
    const bytes = await readFile(here(`../brand/${source}`));
    if (!bytes.length || bytes.length > 2 * 1024 * 1024) throw new Error(`Invalid public brand asset: ${name}`);
    rows.push([name, { type, base64: bytes.toString("base64") }]);
    hashes.push(`// sha256 ${name} ${createHash("sha256").update(bytes).digest("hex")}`);
  }
  return ["// GENERATED by scripts/brand-assets.mjs. Do not edit.", "// Explicit public brand allowlist only; binary bytes are base64 encoded.", ...hashes,
    `export const BRAND_ASSETS = ${JSON.stringify(Object.fromEntries(rows))} as const;`, ""].join("\n");
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await writeFile(MODULE, await brandAssets());
  console.log("Wrote the public brand Worker module.");
}
